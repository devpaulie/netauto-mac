#!/bin/bash
# netauto 전체 설치 — 이것만 실행하면 됩니다.
#   1) 데몬 설치 (sudo 1회 · 실제 전환 담당)
#   2) 메뉴바 앱 설치 (비밀번호 없음 · 로그인 시 자동 시작)
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"

[ "$(id -u)" != "0" ] || { echo "sudo 없이 그냥 ./setup.sh 로 실행하세요 (필요할 때 안에서 물어봅니다)" >&2; exit 1; }

cat <<'INTRO'
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
 netauto 설치

 Wi-Fi 이름에 따라 네트워크 프로필을 자동으로 바꿔줍니다.
 메뉴바에 지금 어떤 프로필인지 표시되고, 거기서 직접 바꿀 수도 있습니다.

 설치되는 것
   · 백그라운드 데몬  — 실제 전환 담당 (로그인 화면에서도 동작)
   · 메뉴바 앱        — 상태 표시 + 조작 + 설정 창

 잠시 뒤 관리자 비밀번호를 한 번 물어봅니다.
 (데몬을 root로 등록해야 이후로 비밀번호가 안 뜹니다)
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
INTRO

# 예전 버전(v1)의 텍스트 설정이 있으면 알려준다
if [ -f /usr/local/etc/netauto.conf ]; then
  echo "참고: 예전 설정 /usr/local/etc/netauto.conf 가 있습니다."
  echo "      새 설정은 /usr/local/etc/netauto/config.json 이며, 예전 파일은 그대로 둡니다."
  echo
fi

printf '계속할까요? [Y/n] '
read -r reply
case "${reply:-Y}" in
  [Nn]*) echo "취소했습니다."; exit 0 ;;
esac
echo

echo "━━ 1/2  데몬 설치 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
sudo "$SRC/install.sh"
echo

echo "━━ 2/2  메뉴바 앱 설치 ━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
"$SRC/install-app.sh"
echo

cat <<'DONE'
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
 끝났습니다.

 메뉴바 오른쪽에 아이콘 + 프로필 이름이 보입니다.
 클릭하면 상태를 보고, 프로필/IP를 바꾸고, 설정을 열 수 있습니다.

 다음에 할 일
   메뉴 › 설정…  에서 Wi-Fi 규칙과 자주 쓰는 IP를 추가하세요.
   현재 규칙:  OfficeWiFi → Office 프로필 + IP 192.168.10.50
              그 외    → Auto 프로필 (DHCP)

 되돌리려면:  ./uninstall-app.sh  그리고  sudo ./uninstall.sh
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
DONE
